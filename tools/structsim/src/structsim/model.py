"""Что получается после шага 2 и что потребляют шаги 3 и 4.

Шаг 2 превращает дерево в **последовательность меток** и попутно делит её на
**блоки**: каждая функция верхнего уровня — отдельный блок, весь остальной
код — ещё один. Блоки нужны третьей мере шага 3: она сопоставляет блок с
блоком, поэтому вынос куска кода в отдельную функцию не роняет оценку.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Span:
    """Где в исходнике стоит то, из чего получилась метка.

    Строки нумеруются с единицы, столбцы с нуля — так их отдаёт
    `semgrep-core -full_token_info`.
    """

    line: int
    column: int
    text: str = ""


@dataclass(frozen=True)
class Block:
    """Один блок программы: функция верхнего уровня либо весь остальной код.

    `name` — имя функции до очистки. На оценку не влияет и нужен только для
    вывода вида «dijkstra ↔ dijkstra — 0.88»; у блока с основным кодом он
    равен None.
    """

    labels: tuple[str, ...]
    name: str | None = None

    def __len__(self) -> int:
        return len(self.labels)


@dataclass(frozen=True)
class Tile:
    """Общий непрерывный кусок меток двух программ, с позициями в обеих.

    То же понятие, что `tile` у JPlag: непрерывный отрезок совпадающих меток,
    не короче заданной длины, и каждая метка покрыта не больше одного раза.
    Позиции — индексы в `Program.labels`, а не строки исходника: меток на
    строки мы пока не отображаем.
    """

    start_a: int
    start_b: int
    length: int

    def labels(self, a: "Program") -> tuple[str, ...]:
        """Сам кусок меток — чтобы тайл можно было прочитать глазами.

        Берётся из первой программы: в обеих он по определению одинаков.
        """
        return a.labels[self.start_a : self.start_a + self.length]


@dataclass(frozen=True)
class Program:
    """Очищенная программа: вся последовательность меток плюс её блоки.

    `labels` — не склейка `blocks`, а именно вся последовательность в порядке
    обхода: первые две меры шага 3 работают по ней, третья — по блокам.
    """

    labels: tuple[str, ...]
    blocks: tuple[Block, ...] = ()
    language: str | None = None
    source: str | None = None
    # Позиции идут ПАРАЛЛЕЛЬНЫМ массивом той же длины, что `labels`, а не
    # внутри меток: сравнение работает по меткам-строкам и про позиции не
    # знает, поэтому добавление позиций не меняет ни одной оценки. У метки от
    # достроенного узла (`FakeTok`) позиции нет — там None. Пустой кортеж
    # означает «позиции не собирались».
    positions: tuple[Span | None, ...] = ()

    def __len__(self) -> int:
        return len(self.labels)

    def span_of(self, start: int, length: int) -> tuple[int, int] | None:
        """Диапазон строк для отрезка меток — то, чем показывается тайл.

        Берётся min и max по тем меткам отрезка, у которых позиция есть.
        Возвращает None, если позиций нет ни у одной.

        Обход дерева идёт в глубину, поэтому непрерывный отрезок меток не
        обязан быть непрерывным куском строк: диапазон может захватить
        строки, которых в отрезке нет.
        """
        lines = [
            span.line
            for span in self.positions[start : start + length]
            if span is not None
        ]
        return (min(lines), max(lines)) if lines else None
